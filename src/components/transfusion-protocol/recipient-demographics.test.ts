import { afterEach, expect, it, vi } from 'vitest';
import { calculateRecipientAge, formatRecipientAge } from './recipient-demographics';

afterEach(() => vi.useRealTimers());

it.each([
  ['2026-10-27', '2026-10-27', '0 дней'],
  ['2026-10-26', '2026-10-27', '1 день'],
  ['2026-10-25', '2026-10-27', '2 дня'],
  ['2026-10-23', '2026-10-27', '4 дня'],
  ['2026-10-22', '2026-10-27', '5 дней'],
  ['2026-10-16', '2026-10-27', '11 дней'],
  ['2026-10-13', '2026-10-27', '14 дней'],
  ['2026-10-06', '2026-10-27', '21 день'],
  ['2026-10-05', '2026-10-27', '22 дня'],
  ['2026-10-02', '2026-10-27', '25 дней'],
  ['2026-09-28', '2026-10-27', '29 дней'],
  ['2026-09-27', '2026-10-27', '1 месяц'],
  ['2026-08-27', '2026-10-27', '2 месяца'],
  ['2026-06-27', '2026-10-27', '4 месяца'],
  ['2026-05-27', '2026-10-27', '5 месяцев'],
  ['2025-11-27', '2026-10-27', '11 месяцев'],
  ['2025-10-28', '2026-10-27', '11 месяцев'],
  ['2025-10-27', '2026-10-27', '1 год'],
  ['2024-10-27', '2026-10-27', '2 года'],
  ['2021-10-27', '2026-10-27', '5 лет'],
  ['2015-10-27', '2026-10-27', '11 лет'],
  ['2005-10-27', '2026-10-27', '21 год'],
  ['2004-10-27', '2026-10-27', '22 года'],
  ['2001-10-27', '2026-10-27', '25 лет'],
  ['2024-02-29', '2024-03-01', '1 день'],
  ['2024-02-29', '2024-03-29', '1 месяц'],
  ['2026-01-31', '2026-02-28', '28 дней'],
  ['2026-01-31', '2026-03-01', '1 месяц'],
  ['2025-12-31', '2026-01-01', '1 день'],
  ['2026-03-08', '2026-03-09', '1 день'],
  ['2026-10-25', '2026-10-26', '1 день'],
])('formats age for %s on %s as %s', (birth, reference, expected) => {
  expect(formatRecipientAge(birth, reference)).toBe(expected);
});

it.each(['', 'not-a-date', '0000-01-01', '2026-02-29', '2026-04-31', '2026-13-01', '2026-10-28'])(
  'omits missing, invalid, or future birth dates: %j',
  (birth) => {
    expect(formatRecipientAge(birth, '2026-10-27')).toBe('');
    expect(calculateRecipientAge(birth, '2026-10-27')).toBeNull();
  },
);

it('uses the local current date when no document date is given and keeps the years API', () => {
  vi.useFakeTimers();
  vi.setSystemTime(new Date(2026, 9, 27, 12));
  expect(formatRecipientAge('2026-10-25')).toBe('2 дня');
  expect(formatRecipientAge('2026-04-27')).toBe('6 месяцев');
  expect(calculateRecipientAge('2026-04-27')).toBe(0);
  expect(calculateRecipientAge('2000-10-28')).toBe(25);
});
